function renterOwnsBooking(row, claims) {
  if (!claims) return true;
  const claimBookingRef = String(claims.booking_ref || "").trim().toLowerCase();
  const rowBookingRef = String(row?.booking_ref || "").trim().toLowerCase();
  if (!claimBookingRef || !rowBookingRef || claimBookingRef !== rowBookingRef) return false;
  const claimEmail = String(claims.email || "").trim().toLowerCase();
  if (claimEmail) {
    const rowEmail = String(row?.customer_email || "").trim().toLowerCase();
    if (rowEmail && rowEmail !== claimEmail) return false;
  }
  const claimPhone = normalizeLookupPhone(claims.phone || "");
  if (claimPhone) {
    const rowPhone = normalizeLookupPhone(row?.customer_phone || row?.renter_phone || "");
    if (rowPhone && rowPhone !== claimPhone) return false;
  }
  return true;
}

/**
 * Escape HTML special characters to prevent XSS in email templates.
 */
function esc(str) {
  if (!str) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}


/**
 * Lookup a booking row from Supabase by booking_ref (canonical bk-... identifier).
 * Returns null when Supabase is unavailable or the row is not found.
 */
async function fetchBookingFromSupabase(bookingRef) {
  const sb = getSupabaseAdmin();
  if (!sb) return null;
  let selectFallbackUsed = false;
  let result = await sb
    .from("bookings")
    .select(BOOKING_SELECT_COLS)
    .eq("booking_ref", bookingRef)
    .maybeSingle();
  if (
    result.error?.code === POSTGRES_UNDEFINED_COLUMN_ERROR ||
    result.error?.code === POSTGREST_SCHEMA_CACHE_ERROR ||
    result.error?.code === POSTGREST_EMBEDDED_SCHEMA_ERROR
  ) {
    selectFallbackUsed = true;
    result = await sb
      .from("bookings")
      .select(BOOKING_SELECT_FALLBACK_COLS)
      .eq("booking_ref", bookingRef)
      .maybeSingle();
  }
  const { data, error } = result;
  if (error) {
    console.error("[manage-booking] BOOKING_LOOKUP_ERROR: queried booking_ref =", bookingRef, "| error.code =", error.code, "| error.message =", error.message);
    return null;
  }
  if (!data) return null;
  return {
    __selectFallbackUsed: selectFallbackUsed,
    manage_token: null,
    balance_payment_link: "",
    pending_change: null,
    has_protection_plan: false,
    protection_plan_tier: null,
    payment_intent_id: null,
    ...data,
  };
}

