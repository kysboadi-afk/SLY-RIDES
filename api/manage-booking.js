function normalizeLookupPhone(value) {
  const digits = String(value || "").replace(/\D+/g, "");
  if (!digits) return "";
  return digits.length === 11 && digits.startsWith("1") ? digits.slice(1) : digits;
}

function normalizeLookupEmail(value) {
  return String(value || "").trim().toLowerCase();
}

function computeCustomerTier(cust = {}) {
  if (cust.banned) return "risky";
  if (cust.flagged || cust.risk_flag === "high" || Number(cust.no_show_count || 0) >= 2) return "risky";
  const totalProfit = cust.total_profit != null ? Number(cust.total_profit) : null;
  const totalBookings = Number(cust.total_bookings || 0);
  if (totalProfit != null && totalProfit < 0) return "unprofitable";
  if (totalProfit != null && totalProfit >= 500 && totalBookings >= 3) return "vip";
  return "standard";
}

function pickLatestCustomer(rows = []) {
  return [...rows].sort((a, b) => {
    const aUpdated = Date.parse(a?.updated_at || a?.created_at || 0) || 0;
    const bUpdated = Date.parse(b?.updated_at || b?.created_at || 0) || 0;
    return bUpdated - aUpdated;
  })[0] || null;
}

async function resolveCustomerTierForBooking(row) {
  const sb = getSupabaseAdmin();
  if (!sb) return "standard";

  const selectCols = "email, phone, risk_flag, flagged, banned, total_profit, total_bookings, no_show_count, updated_at, created_at";
  const normalizedEmail = normalizeLookupEmail(row?.customer_email);
  const normalizedPhone = normalizeLookupPhone(row?.customer_phone);

  try {
    if (normalizedEmail) {
      const { data, error } = await sb
        .from("customers")
        .select(selectCols)
        .ilike("email", normalizedEmail)
        .order("updated_at", { ascending: false, nullsFirst: false })
        .order("created_at", { ascending: false, nullsFirst: false })
        .limit(10);
      if (!error) {
        const exactMatches = (Array.isArray(data) ? data : [])
          .filter((cust) => normalizeLookupEmail(cust?.email) === normalizedEmail);
        const customer = pickLatestCustomer(exactMatches);
        if (customer) return computeCustomerTier(customer);
      }
    }

    if (normalizedPhone) {
      const phoneCandidates = [...new Set([
        String(row?.customer_phone || "").trim(),
        normalizedPhone,
        `+1${normalizedPhone}`,
      ].filter(Boolean))];

      for (const phoneCandidate of phoneCandidates) {
        const { data, error } = await sb
          .from("customers")
          .select(selectCols)
          .eq("phone", phoneCandidate)
          .order("updated_at", { ascending: false, nullsFirst: false })
          .order("created_at", { ascending: false, nullsFirst: false })
          .limit(10);
        if (error) continue;
        const exactMatches = (Array.isArray(data) ? data : [])
          .filter((cust) => normalizeLookupPhone(cust?.phone) === normalizedPhone);
        const customer = pickLatestCustomer(exactMatches);
        if (customer) return computeCustomerTier(customer);
      }
    }
  } catch (customerErr) {
    console.warn("[manage-booking] customer tier lookup failed (non-fatal):", customerErr.message);
  }

  return "standard";
}

function normalizeLookupBookingIdentifier(value) {
  const trimmed = String(value || "").trim().toLowerCase();
  if (!trimmed) return "";
  if (BOOKING_REF_PATTERN.test(trimmed)) return trimmed;
  // Support legacy/non-bk booking identifiers such as historical hex IDs while
  // avoiding phone-number-only inputs.
  if (/^[a-z0-9_-]{8,64}$/.test(trimmed) && /[a-z]/.test(trimmed)) return trimmed;
  return "";
}

function getClientVerifyKey(req, origin, identifier) {
  const xfwd = String(req.headers["x-forwarded-for"] || "").split(",")[0].trim();
  const ip = xfwd || String(req.socket?.remoteAddress || "unknown");
  const id = String(identifier || "").trim().toLowerCase();
  return `${ip}|${origin || "no-origin"}|${id}`;
}

function readVerifyState(key, now = Date.now()) {
  const current = verifyAttempts.get(key);
  if (!current) return { attempts: [] };
  const attempts = (current.attempts || []).filter((ts) => now - ts <= VERIFY_WINDOW_MS);
  const lockUntil = Number(current.lockUntil || 0);
  if (!attempts.length && lockUntil <= now) {
    verifyAttempts.delete(key);
    return { attempts: [] };
  }
  const normalized = { attempts, lockUntil };
  verifyAttempts.set(key, normalized);
  return normalized;
}

function registerVerifyFailure(key, now = Date.now()) {
  const state = readVerifyState(key, now);
  const attempts = [...(state.attempts || []), now].filter((ts) => now - ts <= VERIFY_WINDOW_MS);
  const next = { attempts };
  if (attempts.length >= VERIFY_MAX_ATTEMPTS) {
    next.lockUntil = now + VERIFY_LOCK_MS;
  }
  verifyAttempts.set(key, next);
  return next;
}

function clearVerifyState(key) {
  verifyAttempts.delete(key);
}

