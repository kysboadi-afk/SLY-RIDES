export default async function handler(req, res) {
  const origin = req.headers.origin;
  if (ALLOWED_ORIGINS.includes(origin)) res.setHeader("Access-Control-Allow-Origin", origin);
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type, Authorization");
  if (req.method === "OPTIONS") return res.status(200).end();
  if (req.method !== "POST") return res.status(405).send("Method Not Allowed");

  const body = req.body || {};
  const { action, token } = body;

  if (!action) return res.status(400).json({ error: "action is required" });

  if (action === "verify") {
    const identifier = String(body.identifier || "").trim();
    if (!identifier) return res.status(400).json({ error: "Phone, email, or booking ID is required." });
    const verifyKey = getClientVerifyKey(req, origin, identifier);
    const verifyNow = Date.now();
    const verifyState = readVerifyState(verifyKey, verifyNow);
    if (verifyState.lockUntil && verifyState.lockUntil > verifyNow) {
      const retryAfterSeconds = Math.max(1, Math.ceil((verifyState.lockUntil - verifyNow) / 1000));
      res.setHeader("Retry-After", String(retryAfterSeconds));
      return res.status(429).json({
        error: "Too many verification attempts. Please try again later.",
        retryAfterSeconds,
      });
    }

    const sb = getSupabaseAdmin();
    if (!sb) return res.status(503).json({ error: "Database unavailable." });

    const lookupEmail = identifier.includes("@") ? identifier.toLowerCase() : "";
    const lookupPhone = normalizeLookupPhone(identifier);
    const lookupBookingIdentifier = normalizeLookupBookingIdentifier(identifier);
    const VERIFY_SELECT_COLS = "id, booking_ref, vehicle_id, customer_email, customer_phone, renter_phone, metadata, created_at";
    const VERIFY_SELECT_FALLBACK_COLS = "id, booking_ref, vehicle_id, customer_email, customer_phone, created_at";
    const baseVerifyQuery = (selectCols) => sb
      .from("bookings")
      .select(selectCols)
      .in("status", MANAGE_ELIGIBLE_STATUSES)
      .order("created_at", { ascending: false })
      .limit(100);
    const runVerifyLookup = async (applyFilter) => {
      let result = await applyFilter(baseVerifyQuery(VERIFY_SELECT_COLS));
      if (result.error?.code === POSTGRES_UNDEFINED_COLUMN_ERROR) {
        result = await applyFilter(baseVerifyQuery(VERIFY_SELECT_FALLBACK_COLS));
      }
      return result;
    };

    let candidates = [];
    let lookupErr = null;
    if (lookupEmail) {
      const result = await runVerifyLookup((q) => q.ilike("customer_email", lookupEmail));
      candidates = result.data || [];
      lookupErr = result.error || null;
    } else if (lookupBookingIdentifier) {
      // Check booking identifier BEFORE phone: booking refs like "bk-3bcf479ac6ec"
      // contain digits which would make lookupPhone truthy, causing the wrong
      // branch to run.
      const result = await runVerifyLookup((q) => q);
      candidates = result.data || [];
      lookupErr = result.error || null;
    } else if (lookupPhone) {
      // Fetch all eligible bookings and normalize in JS — stored phones may have
      // formatting chars (parens, dashes, spaces) that break a substring ilike match.
      const result = await runVerifyLookup((q) => q);
      candidates = result.data || [];
      lookupErr = result.error || null;
    } else {
      candidates = [];
    }
    if (lookupErr) {
      registerVerifyFailure(verifyKey);
      console.error("manage-booking verify lookup error:", lookupErr.message);
      return res.status(500).json({ error: "Could not verify booking right now." });
    }

    const matches = (candidates || []).filter((row) => {
      const metadata = row && typeof row.metadata === "object" && row.metadata ? row.metadata : {};
      const rowEmails = [
        row.customer_email,
        row.renter_email,
        row.email,
        metadata.customer_email,
        metadata.renter_email,
        metadata.email,
      ]
        .map((v) => String(v || "").trim().toLowerCase())
        .filter(Boolean);
      const rowPhones = [
        row.customer_phone,
        row.renter_phone,
        row.phone,
        metadata.customer_phone,
        metadata.renter_phone,
        metadata.phone,
      ]
        .map((v) => normalizeLookupPhone(v))
        .filter(Boolean);
      const rowBookingRef = String(row.booking_ref || "").trim().toLowerCase();
      const rowLegacyId = String(row.id || "").trim().toLowerCase();
      if (lookupEmail)      return rowEmails.includes(lookupEmail);
      // Check booking identifier BEFORE phone so mixed IDs don't get interpreted as phones.
      if (lookupBookingIdentifier) {
        return (!!rowBookingRef && rowBookingRef === lookupBookingIdentifier)
          || (!!rowLegacyId && rowLegacyId === lookupBookingIdentifier);
      }
      if (lookupPhone)      return rowPhones.includes(lookupPhone);
      return false;
    });

    if (!matches.length) {
      registerVerifyFailure(verifyKey);
      return res.status(404).json({ error: "No eligible booking was found with that phone, email, or booking ID." });
    }

    // Use the most recent eligible booking (results are already ordered by created_at desc).
    const selected = matches[0];
    clearVerifyState(verifyKey);

    const selectedBookingIdentifier = String(selected.booking_ref || selected.id || "").trim();
    if (!selectedBookingIdentifier) {
      registerVerifyFailure(verifyKey);
      return res.status(500).json({ error: "Could not verify booking right now." });
    }
    const manageToken = createManageToken(selectedBookingIdentifier);
    const renterSessionToken = createRenterSessionToken({
      bookingRef: selectedBookingIdentifier,
      email: selected.customer_email || "",
      phone: selected.customer_phone || selected.renter_phone || "",
      authMethod: "verify_identifier",
    });
    console.log("[manage-booking] VERIFY: booking_ref =", selectedBookingIdentifier, "| token =", manageToken);
    try {
      await sb
        .from("bookings")
        .update({ manage_token: manageToken, updated_at: new Date().toISOString() })
        .eq("booking_ref", selected.booking_ref || selectedBookingIdentifier);
    } catch (tokenErr) {
      console.warn("manage-booking verify: failed to persist manage token (non-fatal):", tokenErr.message);
    }

    return res.status(200).json({
      verified: true,
      token: manageToken,
      renterSessionToken: renterSessionToken || null,
      bookingId: selectedBookingIdentifier,
      vehicleId: uiVehicleId(selected.vehicle_id || ""),
    });
  }

  const bearerToken = extractBearerToken(req);
  const renterClaims = verifyRenterSessionToken(bearerToken);

  let bookingId = "";
  if (token) {
    bookingId = verifyManageToken(token) || "";
    if (!bookingId) {
      return res.status(401).json({ error: "Invalid or expired manage token. Please verify again, or contact support if your old link no longer works." });
    }
  } else if (renterClaims?.booking_ref) {
    bookingId = String(renterClaims.booking_ref || "").trim();
  } else {
    return res.status(401).json({ error: "manage_token or renter session is required" });
  }

  // ── action: get ─────────────────────────────────────────────────────────────
  if (action === "get") {
    console.log("[manage-booking] TOKEN:", bookingId);

    // 1. Primary lookup: Supabase by booking_ref
    let row = await fetchBookingFromSupabase(bookingId);
    console.log("[manage-booking] GET: fetchBookingFromSupabase(", bookingId, ") =", row ? "FOUND" : "NULL");

    // 2. Safety fallback: Supabase by payment_intent_id
    if (!row) row = await fetchBookingByIdFromSupabase(bookingId);
    if (!row) row = await fetchBookingByPaymentIntentFromSupabase(bookingId);

    // 3. Last-resort fallback: bookings.json (legacy GitHub-stored bookings)
    if (!row) {
      console.warn("[manage-booking] Supabase miss → fallback used", bookingId);
      try {
        const { data } = await loadBookings();
        vehicleLoop: for (const vehicleId of Object.keys(data)) {
          const match = data[vehicleId].find(
            (b) => b.bookingId === bookingId || b.paymentIntentId === bookingId
          );
          if (match) {
            console.warn("[manage-booking] Supabase miss → fallback used", bookingId);
            row = {
              booking_ref:       match.bookingId,
              vehicle_id:        match.vehicleId,
              pickup_date:       match.pickupDate,
              return_date:       match.returnDate,
              pickup_time:       match.pickupTime,
              return_time:       match.returnTime,
              status:            match.status,
              payment_status:    "partial",
              total_price:       match.totalPrice,
              deposit_paid:      match.depositPaid || 0,
              remaining_balance: match.balanceDue  || 0,
              customer_name:     match.name,
              customer_email:    match.email,
              customer_phone:    match.phone,
              change_count:      match.extensionCount || 0,
            };
            break vehicleLoop;
          }
        }
      } catch (jsonErr) {
        console.warn("[manage-booking] bookings.json fallback failed (non-fatal):", jsonErr.message);
      }
    }

    console.log("[manage-booking] RESULT:", row);
    if (!row) return res.status(404).json({ error: "Booking not found" });
    if (!renterOwnsBooking(row, renterClaims)) {
      return res.status(403).json({ error: "Renter session does not match this booking." });
    }

    const vehicleId = uiVehicleId(row.vehicle_id || "");
    const vehicleData = vehicleId ? await getVehicleById(vehicleId) : null;

    // Guard against data-integrity issues where remaining_balance was stored as 0
    // even though the customer hasn't paid the full amount (e.g. reserved_unpaid bookings
    // where amountPaid was conflated with totalPrice during sync).
    const totalPriceNum  = Number(row.total_price   || 0);
    const depositPaidNum = Number(row.deposit_paid  || 0);
    const staleBalanceFallbackUsed = Number(row.remaining_balance || 0) === 0
      && totalPriceNum > 0
      && depositPaidNum < totalPriceNum;
    let balanceDue       = effectiveBalanceDue(row);
    let resolvedTotal    = totalPriceNum;
    let pricingFallbackUsed = false;

    // When remaining_balance is stale zero AND total_price equals the deposit amount
    // (e.g. older bookings where full_rental_amount was absent from PI metadata so
    // the webhook stored total_price = deposit_amount), fall back to live vehicle
    // pricing so the manage-booking dashboard shows the correct outstanding balance
    // and the customer can pay online.  This mirrors the identical fallback already
    // present in the create_balance_payment_intent action below.
    if (balanceDue <= 0 && hasPartialBalancePaymentStatus(row.payment_status) && vehicleData && row.pickup_date && row.return_date) {
      try {
        const repriced = await recomputePricing(
          vehicleData,
          row.pickup_date,
          row.return_date,
          !!row.has_protection_plan,
          row.protection_plan_tier || null,
          depositPaidNum
        );
        if (repriced && repriced.newBalanceDue > 0) {
          balanceDue    = repriced.newBalanceDue;
          resolvedTotal = repriced.newTotal;
          pricingFallbackUsed = true;
        }
      } catch (repErr) {
        console.warn("[manage-booking] get: pricing fallback for stale balance failed (non-fatal):", repErr.message);
      }
    }

    const paymentPlan = await fetchPaymentPlanSummary(getSupabaseAdmin(), bookingId, {
      missingTableErrorCode: POSTGRES_UNDEFINED_TABLE_ERROR,
    });
    const lifecycle = deriveBookingPaymentLifecycle({
      status: row.status,
      paymentStatus: row.payment_status,
      category: row.category,
      totalAmount: resolvedTotal,
      amountPaid: depositPaidNum,
      remainingBalance: balanceDue,
      paymentPlan,
    });
    const contractTransitionObservability = buildManageBookingObservability({
      row,
      bookingId,
      resolvedTotal,
      depositPaid: depositPaidNum,
      balanceDue,
      lifecycle,
      staleBalanceFallbackUsed,
      pricingFallbackUsed,
    });
    if (contractTransitionObservability.fallbackPaths.length > 0) {
      logManageBookingContractTransition("fallback_path_used", {
        booking_id: bookingId,
        fallback_paths: contractTransitionObservability.fallbackPaths,
      });
    }
    logManageBookingContractTransition("legacy_derivation_surface_exposed", {
      booking_id: bookingId,
      surfaces: contractTransitionObservability.surfacesUsingLegacyDerivations,
    });
    const agreementSummary = await loadBookingAgreementSummary(getSupabaseAdmin(), bookingId);
    const customerTier = await resolveCustomerTierForBooking(row);

    // Count how many completed (non-cancelled) bookings this renter has in total,
    // so the frontend can decide whether to show the partial payment option.
    let renterBookingCount = 0;
    const renterEmail = (row.customer_email || "").trim().toLowerCase();
    if (renterEmail) {
      const sb = getSupabaseAdmin();
      if (sb) {
        try {
          const { count } = await sb
            .from("bookings")
            .select("booking_ref", { count: "exact", head: true })
            .ilike("customer_email", renterEmail)
            .not("status", "in", '("cancelled","canceled","rejected","declined")');
          if (Number.isFinite(count)) renterBookingCount = count;
        } catch (countErr) {
          console.warn("[manage-booking] renterBookingCount query failed (non-fatal):", countErr.message);
        }
      }
    }

    return res.status(200).json({
      bookingId,
      vehicleId,
      vehicleName:  vehicleData?.name  || vehicleId,
      vehicleYear:  vehicleData?.year  || null,
      vehicleMake:  vehicleData?.make  || null,
      vehicleModel: vehicleData?.model || null,
      vehicleColor: vehicleData?.color || null,
      pickupDate:  row.pickup_date,
      returnDate:  row.return_date,
      pickupTime:  row.pickup_time,
      returnTime:  row.return_time,
      status:      row.status,
      paymentStatus: row.payment_status,
      category:      row.category || null,
      identitySessionId: row.identity_session_id || null,
      totalPrice:    resolvedTotal,
      depositPaid:   depositPaidNum,
      balanceDue,
      customerName:  row.customer_name || "",
      customerEmail: row.customer_email || "",
      customerPhone: row.customer_phone || "",
      changeCount:   Number(row.change_count  || 0),
      balancePaymentLink: row.balance_payment_link || null,
      hasProtectionPlan: !!row.has_protection_plan,
      protectionPlanTier: row.protection_plan_tier || null,
      paymentPlan,
      paymentLifecycleState: lifecycle.lifecycleState,
      canPayRemainingOnline: lifecycle.canPayRemainingOnline,
      isReservationStage: lifecycle.isReservationStage,
      isActiveRentalStage: lifecycle.isActiveRental,
      isOverdueStage: lifecycle.isOverdue,
      isPickupDueStage: lifecycle.isManualPickup && lifecycle.lifecycleState === "pickup_due",
      lateFeeStatus: row.late_fee_status || null,
      lateFeeAmount: resolveVisibleLateFeeAmount(row.late_fee_status, row.late_fee_amount),
      extensionRiskOverride: row.extension_risk_override || null,
      currentAgreement: agreementSummary.currentAgreement,
      agreements: agreementSummary.agreements,
      contractTransitionObservability,
      customerTier,
      isVipClient: customerTier === "vip",
      renterBookingCount,
    });
  }

  if (action === "create_balance_payment_intent") {
    if (!process.env.STRIPE_SECRET_KEY) {
      return res.status(500).json({ error: "Payment processing is temporarily unavailable. Please contact us at (844) 511-4059." });
    }
    if (!process.env.STRIPE_PUBLISHABLE_KEY) {
      return res.status(500).json({ error: "Payment processing is temporarily unavailable. Please contact us at (844) 511-4059." });
    }
    let row = await fetchBookingFromSupabase(bookingId);
    if (!row) row = await fetchBookingByIdFromSupabase(bookingId);
    if (!row) row = await fetchBookingByPaymentIntentFromSupabase(bookingId);
    if (!row) {
      try {
        const { data } = await loadBookings();
        vehicleLoop: for (const vehicleId of Object.keys(data || {})) {
          const match = (data[vehicleId] || []).find(
            (b) => b.bookingId === bookingId || b.paymentIntentId === bookingId
          );
          if (match) {
            row = {
              booking_ref:       match.bookingId,
              vehicle_id:        match.vehicleId,
              pickup_date:       match.pickupDate,
              return_date:       match.returnDate,
              pickup_time:       match.pickupTime,
              return_time:       match.returnTime,
              status:            match.status,
              payment_status:    "partial",
              total_price:       match.totalPrice,
              deposit_paid:      match.depositPaid || 0,
              remaining_balance: match.balanceDue  || 0,
              customer_name:     match.name,
              customer_email:    match.email,
              customer_phone:    match.phone,
              change_count:      match.extensionCount || 0,
            };
            break vehicleLoop;
          }
        }
      } catch (jsonErr) {
        console.warn("[manage-booking] create_balance_payment_intent: bookings.json fallback failed (non-fatal):", jsonErr.message);
      }
    }
    if (!row) return res.status(404).json({ error: "Booking not found" });
    if (!renterOwnsBooking(row, renterClaims)) {
      return res.status(403).json({ error: "Renter session does not match this booking." });
    }
    const canonicalBookingId = String(row.booking_ref || bookingId || "").trim() || bookingId;
    if (!MANAGE_ELIGIBLE_STATUSES.includes(row.status)) {
      return res.status(409).json({ error: "This booking is not eligible for balance payment." });
    }
    let resolvedBalance = effectiveBalanceDue(row);

    // Load vehicle data early — needed both for the pricing fallback below and
    // for the Stripe PI description / metadata further down.
    const uiVehicle = uiVehicleId(row.vehicle_id || "");
    const vehicleData = uiVehicle ? await getVehicleById(uiVehicle) : null;

    // The booking row fields (total_price, remaining_balance) can be 0 when the
    // balance is tracked exclusively via the ledger system.  Fall back to the
    // ledger's remaining_balance so renters are never incorrectly told there is
    // nothing to pay.
    if (!Number.isFinite(resolvedBalance) || resolvedBalance <= 0) {
      try {
        const ledger = await getLedgerSummary(getSupabaseAdmin(), { bookingId: canonicalBookingId });
        const ledgerBalance = Number(ledger.remaining_balance || 0);
        if (Number.isFinite(ledgerBalance) && ledgerBalance > 0) {
          resolvedBalance = ledgerBalance;
        }
      } catch (ledgerErr) {
        console.warn("[manage-booking] create_balance_payment_intent: ledger fallback failed:", ledgerErr.message);
      }
    }

    // Final fallback: for reservation-deposit bookings where the DB stored
    // total_price = deposit_paid (because full_rental_amount was absent from the
    // PI metadata) and no ledger entry was written, recompute from live pricing
    // so the customer can still pay the outstanding balance online.
    if ((!Number.isFinite(resolvedBalance) || resolvedBalance <= 0) && hasPartialBalancePaymentStatus(row.payment_status) && vehicleData && row.pickup_date && row.return_date) {
      try {
        const repriced = await recomputePricing(
          vehicleData,
          row.pickup_date,
          row.return_date,
          !!row.has_protection_plan,
          row.protection_plan_tier || null,
          Number(row.deposit_paid || 0)
        );
        if (repriced && repriced.newBalanceDue > 0) {
          resolvedBalance = repriced.newBalanceDue;
        }
      } catch (repErr) {
        console.warn("[manage-booking] create_balance_payment_intent: pricing fallback failed:", repErr.message);
      }
    }

    if (!Number.isFinite(resolvedBalance) || resolvedBalance <= 0) {
      return res.status(409).json({ error: "No balance is due for this booking." });
    }

    // Optional partial payment amount — capped server-side to resolvedBalance
    let paymentAmount = resolvedBalance;
    if (body.payment_amount !== undefined && body.payment_amount !== null) {
      const requested = Math.round(Number(body.payment_amount) * 100) / 100;
      if (!Number.isFinite(requested) || requested <= 0) {
        return res.status(400).json({ error: "payment_amount must be a positive number." });
      }
      if (requested > resolvedBalance) {
        return res.status(400).json({
          error: `Payment amount ($${requested.toFixed(2)}) exceeds remaining balance ($${resolvedBalance.toFixed(2)}).`,
        });
      }
      paymentAmount = requested;
    }
    const isPartialPayment = Math.round(paymentAmount * 100) < Math.round(resolvedBalance * 100);
    if (isPartialPayment) {
      const customerTier = await resolveCustomerTierForBooking(row);
      if (customerTier !== "vip") {
        return res.status(403).json({ error: "Partial balance payments are only available to VIP clients." });
      }
    }
    const stripe = new Stripe(process.env.STRIPE_SECRET_KEY);
    const paymentIntent = await stripe.paymentIntents.create({
      amount: Math.round(paymentAmount * 100),
      currency: "usd",
      receipt_email: row.customer_email || undefined,
      description: `Sly Car Rentals LLC – ${vehicleData?.name || uiVehicle || "Rental"} ${isPartialPayment ? "Partial " : ""}Balance Payment`,
      automatic_payment_methods: { enabled: true },
      metadata: {
        payment_type: isPartialPayment ? "partial_balance" : "rental_balance",
        booking_id: canonicalBookingId,
        original_booking_id: canonicalBookingId,
        vehicle_id: uiVehicle || "",
        vehicle_name: vehicleData?.name || uiVehicle || "",
        renter_name: row.customer_name || "",
        renter_phone: row.customer_phone || "",
        email: row.customer_email || "",
        pickup_date: row.pickup_date || "",
        return_date: row.return_date || "",
        remaining_balance: String(resolvedBalance),
        payment_amount: String(paymentAmount),
        remaining_after_payment: isPartialPayment
          ? String(Math.max(0, Math.round((resolvedBalance - paymentAmount) * 100) / 100))
          : "0",
      },
    });
    return res.status(200).json({
      clientSecret: paymentIntent.client_secret,
      publishableKey: process.env.STRIPE_PUBLISHABLE_KEY,
      balanceAmount: resolvedBalance,
      paymentAmount,
      isPartialPayment,
    });
  }

  if (action === "get_agreement_url") {
    const sb = getSupabaseAdmin();
    if (!sb) return res.status(503).json({ error: "Database unavailable" });
    const agreementDetails = await loadAgreementPathForDownload(sb, bookingId);
    if (!agreementDetails?.path) {
      return res.status(404).json({ error: "No agreement PDF found for this booking." });
    }

    const storage = sb.storage?.from?.("rental-agreements");
    if (!storage?.createSignedUrl) {
      return res.status(503).json({ error: "Document storage is unavailable right now." });
    }

    const { data: signedData, error: signedErr } = await storage.createSignedUrl(agreementDetails.path, 3600);
    if (signedErr) {
      console.error("manage-booking agreement signed-url error:", signedErr.message);
      return res.status(500).json({ error: "Could not load the agreement right now." });
    }

    return res.status(200).json({
      url: signedData?.signedUrl || null,
      path: agreementDetails.path,
      currentAgreement: agreementDetails.currentAgreement || null,
      agreements: agreementDetails.agreements || [],
    });
  }

  // ── action: check_availability ──────────────────────────────────────────────
  if (action === "check_availability") {
    const row = await fetchBookingFromSupabase(bookingId);
    if (!row) return res.status(404).json({ error: "Booking not found" });
    if (!renterOwnsBooking(row, renterClaims)) {
      return res.status(403).json({ error: "Renter session does not match this booking." });
    }

    const {
      newPickupDate, newReturnDate,
      newPickupTime, newReturnTime,
      newVehicleId, newProtectionPlan, newProtectionPlanTier,
    } = body;

    if (!newPickupDate || !newReturnDate) {
      return res.status(400).json({ error: "newPickupDate and newReturnDate are required" });
    }

    const targetVehicleUiId = newVehicleId || uiVehicleId(row.vehicle_id || "");
    const vehicleData = await getVehicleById(targetVehicleUiId);
    if (!vehicleData) return res.status(400).json({ error: "Invalid vehicle" });

    // Check availability, excluding this booking's own current range
    const ranges = await loadBookedRanges(targetVehicleUiId);
    const otherRanges = ranges.filter(
      (r) => !(r.from === row.pickup_date && r.to === row.return_date)
    );

    const fPickupTime  = normalizeClockTime(newPickupTime)  || null;
    const fReturnTime  = normalizeClockTime(newReturnTime)  || null;
    const conflict = hasDateTimeOverlap(otherRanges, newPickupDate, newReturnDate, fPickupTime, fReturnTime);

    if (conflict) {
      return res.status(200).json({
        available: false,
        reason: "The requested dates are not available for this vehicle.",
      });
    }

    const depositPaid  = Number(row.deposit_paid || 0);
    const hasProtection = newProtectionPlan !== undefined ? !!newProtectionPlan : false;
    const tier = newProtectionPlanTier || null;

    const pricing = await recomputePricing(vehicleData, newPickupDate, newReturnDate, hasProtection, tier, depositPaid);
    if (!pricing) return res.status(400).json({ error: "Could not compute pricing for this vehicle" });

    const settings = await loadPricingSettings();
    const changeFeeRequired = Number(row.change_count || 0) > 0;
    const changeFee = changeFeeRequired ? (settings.booking_change_fee || 25) : 0;

    return res.status(200).json({
      available: true,
      newTotal:     pricing.newTotal,
      newBalanceDue: pricing.newBalanceDue,
      changeFeeRequired,
      changeFee,
    });
  }

  // ── action: apply_change ────────────────────────────────────────────────────
  if (action === "apply_change") {
    const row = await fetchBookingFromSupabase(bookingId);
    if (!row) return res.status(404).json({ error: "Booking not found" });
    if (!renterOwnsBooking(row, renterClaims)) {
      return res.status(403).json({ error: "Renter session does not match this booking." });
    }

    // Only free (first) changes allowed here
    const changeCount = Number(row.change_count || 0);
    if (changeCount > 0) {
      return res.status(402).json({
        error: "A change fee is required for additional changes.",
        requiresChangeFee: true,
      });
    }

    const {
      newPickupDate, newReturnDate,
      newPickupTime, newReturnTime,
      newVehicleId, newProtectionPlan, newProtectionPlanTier,
    } = body;

    if (!newPickupDate || !newReturnDate) {
      return res.status(400).json({ error: "newPickupDate and newReturnDate are required" });
    }

    const targetVehicleUiId = newVehicleId || uiVehicleId(row.vehicle_id || "");
    const vehicleData = await getVehicleById(targetVehicleUiId);
    if (!vehicleData) return res.status(400).json({ error: "Invalid vehicle" });

    // Availability check (exclude own range)
    const ranges = await loadBookedRanges(targetVehicleUiId);
    const otherRanges = ranges.filter(
      (r) => !(r.from === row.pickup_date && r.to === row.return_date)
    );
    const fPickupTime = normalizeClockTime(newPickupTime) || null;
    const fReturnTime = normalizeClockTime(newReturnTime) || null;
    if (hasDateTimeOverlap(otherRanges, newPickupDate, newReturnDate, fPickupTime, fReturnTime)) {
      return res.status(409).json({ error: "The requested dates are not available for this vehicle." });
    }

    const depositPaid = Number(row.deposit_paid || 0);
    const hasProtection = newProtectionPlan !== undefined ? !!newProtectionPlan : false;
    const tier = newProtectionPlanTier || null;
    const pricing = await recomputePricing(vehicleData, newPickupDate, newReturnDate, hasProtection, tier, depositPaid);
    if (!pricing) return res.status(400).json({ error: "Could not compute pricing for this vehicle" });

    // Build new balance link
    const newBalanceLink = buildBalanceLink(bookingId, {
      ...row,
      pickup_date:      newPickupDate,
      return_date:      newReturnDate,
      vehicle_id:       normalizeVehicleId(targetVehicleUiId),
    }, targetVehicleUiId);

    // Update Supabase bookings row
    const sb = getSupabaseAdmin();
    if (!sb) return res.status(503).json({ error: "Database unavailable" });

    const shouldPersistProtectionPlan = !row.__selectFallbackUsed;

    const applyChangeUpdate = {
      vehicle_id:          normalizeVehicleId(targetVehicleUiId),
      pickup_date:         newPickupDate,
      return_date:         newReturnDate,
      pickup_time:         fPickupTime || row.pickup_time,
      return_time:         fReturnTime || row.return_time,
      total_price:         pricing.newTotal,
      remaining_balance:   pricing.newBalanceDue,
      change_count:        changeCount + 1,
      balance_payment_link: newBalanceLink,
      updated_at:          new Date().toISOString(),
    };
    if (shouldPersistProtectionPlan) {
      applyChangeUpdate.has_protection_plan = hasProtection;
      applyChangeUpdate.protection_plan_tier = hasProtection ? (tier || null) : null;
    }

    let { error: sbErr } = await sb
      .from("bookings")
      .update(applyChangeUpdate)
      .eq("booking_ref", bookingId);

    if (
      sbErr &&
      (isMissingColumnCompatError(sbErr, "has_protection_plan") ||
        isMissingColumnCompatError(sbErr, "protection_plan_tier"))
    ) {
      const legacyApplyChangeUpdate = { ...applyChangeUpdate };
      delete legacyApplyChangeUpdate.has_protection_plan;
      delete legacyApplyChangeUpdate.protection_plan_tier;
      console.warn(
        "manage-booking apply_change retrying update without protection plan columns:",
        sbErr.message
      );
      const retryResult = await sb
        .from("bookings")
        .update(legacyApplyChangeUpdate)
        .eq("booking_ref", bookingId);
      sbErr = retryResult.error || null;
    }

    if (sbErr) {
      console.error(
        "manage-booking apply_change Supabase update error:",
        sbErr.message,
        "| code:", sbErr.code,
        "| details:", sbErr.details,
        "| hint:", sbErr.hint
      );
      return res.status(500).json({ error: "Failed to save booking change" });
    }

    // Update booked-dates.json (disabled, Phase 4 — no-op)
    try {
      await updateBookedDates(
        targetVehicleUiId,
        row.pickup_date, row.return_date,
        newPickupDate, newReturnDate,
        fPickupTime || "", fReturnTime || ""
      );
    } catch (dateErr) {
      console.error("manage-booking apply_change booked-dates update error (non-fatal):", dateErr.message);
    }

    // Sync blocked_dates in Supabase (Phase 4: primary availability source).
    // extendBlockedDateForBooking updates end_date; also update start_date when
    // the pickup date changed (e.g., renter shortens the rental window).
    try {
      await extendBlockedDateForBooking(
        normalizeVehicleId(targetVehicleUiId),
        bookingId,
        newReturnDate,
        fReturnTime || null
      );
      if (newPickupDate !== row.pickup_date && sb) {
        const { error: startUpdateErr } = await sb
          .from("blocked_dates")
          .update({ start_date: newPickupDate })
          .eq("vehicle_id", normalizeVehicleId(targetVehicleUiId))
          .eq("booking_ref", bookingId)
          .eq("reason", "booking");
        if (startUpdateErr) {
          console.warn("manage-booking apply_change blocked_dates start_date update failed (non-fatal):", startUpdateErr.message);
        }
      }
    } catch (blockedErr) {
      console.error("manage-booking apply_change blocked_dates sync error (non-fatal):", blockedErr.message);
    }

    // Update bookings.json (legacy store)
    try {
      const currentVehicleUiId = uiVehicleId(row.vehicle_id || "");
      await updateBooking(currentVehicleUiId, bookingId, {
        vehicleId:           targetVehicleUiId,
        pickupDate:          newPickupDate,
        returnDate:          newReturnDate,
        pickupTime:          fPickupTime || undefined,
        returnTime:          fReturnTime || undefined,
        totalPrice:          pricing.newTotal,
        remainingBalance:    pricing.newBalanceDue,
        balancePaymentLink:  newBalanceLink,
        updatedAt:           new Date().toISOString(),
      });
    } catch (jsonErr) {
      console.error("manage-booking apply_change bookings.json update error (non-fatal):", jsonErr.message);
    }

    // Audit log
    try {
      await writeAuditLog(bookingId, [
        { field: "pickup_date",    oldValue: row.pickup_date,  newValue: newPickupDate },
        { field: "return_date",    oldValue: row.return_date,  newValue: newReturnDate },
        { field: "vehicle_id",     oldValue: row.vehicle_id,   newValue: normalizeVehicleId(targetVehicleUiId) },
        { field: "total_price",    oldValue: String(row.total_price), newValue: String(pricing.newTotal) },
        { field: "remaining_balance", oldValue: String(row.remaining_balance), newValue: String(pricing.newBalanceDue) },
        { field: "change_count",   oldValue: String(changeCount), newValue: String(changeCount + 1) },
      ], "customer");
    } catch (auditErr) {
      console.error("manage-booking apply_change audit log error (non-fatal):", auditErr.message);
    }

    // Send confirmation email
    const updatedRow = await fetchBookingFromSupabase(bookingId);
    if (updatedRow?.customer_email) {
      await sendChangeConfirmationEmail({
        renterEmail:  updatedRow.customer_email,
        renterName:   "",
        vehicleName:  vehicleData.name,
        newPickupDate,
        newReturnDate,
        newTotal:     pricing.newTotal,
        newBalanceDue: pricing.newBalanceDue,
        balanceLink:  newBalanceLink,
      });
    }

    return res.status(200).json({
      success: true,
      newPickupDate,
      newReturnDate,
      newTotal:         pricing.newTotal,
      newBalanceDue:    pricing.newBalanceDue,
      balancePaymentLink: newBalanceLink,
      changeCount:      changeCount + 1,
    });
  }

  // ── action: initiate_paid_change ─────────────────────────────────────────────
  if (action === "initiate_paid_change") {
    if (!process.env.STRIPE_SECRET_KEY) {
      console.error("manage-booking initiate_paid_change: STRIPE_SECRET_KEY is not set");
      return res.status(500).json({ error: "Payment processing is temporarily unavailable. Please contact us at (844) 511-4059." });
    }
    if (!process.env.STRIPE_PUBLISHABLE_KEY) {
      console.error("manage-booking initiate_paid_change: STRIPE_PUBLISHABLE_KEY is not set");
      return res.status(500).json({ error: "Payment processing is temporarily unavailable. Please contact us at (844) 511-4059." });
    }

    const row = await fetchBookingFromSupabase(bookingId);
    if (!row) return res.status(404).json({ error: "Booking not found" });
    if (!renterOwnsBooking(row, renterClaims)) {
      return res.status(403).json({ error: "Renter session does not match this booking." });
    }

    const {
      newPickupDate, newReturnDate,
      newPickupTime, newReturnTime,
      newVehicleId, newProtectionPlan, newProtectionPlanTier,
    } = body;

    if (!newPickupDate || !newReturnDate) {
      return res.status(400).json({ error: "newPickupDate and newReturnDate are required" });
    }

    const targetVehicleUiId = newVehicleId || uiVehicleId(row.vehicle_id || "");
    const vehicleData = await getVehicleById(targetVehicleUiId);
    if (!vehicleData) return res.status(400).json({ error: "Invalid vehicle" });

    // Availability check
    const ranges = await loadBookedRanges(targetVehicleUiId);
    const otherRanges = ranges.filter(
      (r) => !(r.from === row.pickup_date && r.to === row.return_date)
    );
    const fPickupTime = normalizeClockTime(newPickupTime) || null;
    const fReturnTime = normalizeClockTime(newReturnTime) || null;
    if (hasDateTimeOverlap(otherRanges, newPickupDate, newReturnDate, fPickupTime, fReturnTime)) {
      return res.status(409).json({ error: "The requested dates are not available for this vehicle." });
    }

    const settings = await loadPricingSettings();
    const changeFee = settings.booking_change_fee || 25;

    // Persist the pending change to Supabase
    const sb = getSupabaseAdmin();
    if (!sb) return res.status(503).json({ error: "Database unavailable" });

    const pendingChange = {
      newPickupDate, newReturnDate,
      newPickupTime: fPickupTime,
      newReturnTime: fReturnTime,
      newVehicleId:  normalizeVehicleId(targetVehicleUiId),
      newProtectionPlan:   !!newProtectionPlan,
      newProtectionPlanTier: newProtectionPlanTier || null,
      initiatedAt: new Date().toISOString(),
    };

    const { error: sbErr } = await sb
      .from("bookings")
      .update({
        pending_change: pendingChange,
        updated_at: new Date().toISOString(),
      })
      .eq("booking_ref", bookingId);

    if (sbErr) {
      console.error("manage-booking initiate_paid_change Supabase update error:", sbErr.message);
      return res.status(500).json({ error: "Failed to store pending change" });
    }

    // Create Stripe PaymentIntent for the change fee
    const stripe = new Stripe(process.env.STRIPE_SECRET_KEY);
    const paymentIntent = await stripe.paymentIntents.create({
      amount: Math.round(changeFee * 100),
      currency: "usd",
      receipt_email: row.customer_email || undefined,
      description: `Sly Car Rentals LLC – Booking Change Fee (${bookingId})`,
      automatic_payment_methods: { enabled: true },
      metadata: {
        payment_type:    "booking_change_fee",
        booking_id:      bookingId,
        vehicle_id:      normalizeVehicleId(targetVehicleUiId),
        change_fee:      String(changeFee),
      },
    });

    return res.status(200).json({
      clientSecret:    paymentIntent.client_secret,
      publishableKey:  process.env.STRIPE_PUBLISHABLE_KEY,
      changeFee,
    });
  }

  return res.status(400).json({ error: `Unknown action: ${action}` });
}
