/**
 * Compute the effective balance due for a booking row.
 * Guards against data-integrity issues where remaining_balance was stored as 0
 * even though the customer hasn't paid the full amount (e.g. reserved_unpaid
 * bookings where amountPaid was conflated with totalPrice during sync).
 */
function effectiveBalanceDue(row) {
  const totalPrice  = Number(row.total_price   || 0);
  const depositPaid = Number(row.deposit_paid  || 0);
  let   balance     = Number(row.remaining_balance || 0);
  if (balance === 0 && totalPrice > 0 && depositPaid < totalPrice) {
    balance = Math.round((totalPrice - depositPaid) * 100) / 100;
  }
  return balance;
}

